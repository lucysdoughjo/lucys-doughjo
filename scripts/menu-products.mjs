export function toSanityProduct(p) {
  const doc = {
    _id: p._id,
    _type: "product",
    name: p.name,
    slug: { _type: "slug", current: p.slug },
    category: { _type: "reference", _ref: p.categoryRef },
    description: p.description,
    priceCents: p.priceCents,
    unitsPerItem: p.unitsPerItem,
    unitLabel: p.unitLabel,
    availableThisWeek: true,
    soldOut: false,
  };
  if (p.priceTiers) doc.priceTiers = p.priceTiers;
  return doc;
}
